import { readFile, writeFile, mkdir } from "node:fs/promises";
try {
  process.loadEnvFile(".env.local");
} catch {}
const headers = {
  "User-Agent": process.env.SEC_USER_AGENT,
  Accept: "text/html,application/json",
};
const wait = () => new Promise((r) => setTimeout(r, 400));
const report = [];
for (const ticker of ["AAPL", "GOOGL", "AMZN"]) {
  const normalized = JSON.parse(
      await readFile(`.local/live/${ticker}.json`, "utf8"),
    ),
    period = normalized.annual.at(-1),
    cik = normalized.cik;
  const accn = period.metrics.revenue.sources[0].accession;
  await wait();
  const sr = await fetch(`https://data.sec.gov/submissions/CIK${cik}.json`, {
    headers,
  });
  if (!sr.ok) throw new Error(`${ticker} submissions HTTP ${sr.status}`);
  const sub = await sr.json(),
    recent = sub.filings.recent,
    index = recent.accessionNumber.indexOf(accn);
  if (index < 0)
    throw new Error("Annual filing not in current submission history.");
  const url = `https://www.sec.gov/Archives/edgar/data/${Number(cik)}/${accn.replaceAll("-", "")}/${recent.primaryDocument[index]}`;
  await wait();
  const response = await fetch(url, { headers });
  if (!response.ok)
    throw new Error(`${ticker} official filing HTTP ${response.status}`);
  const html = await response.text();
  await mkdir(".local/live", { recursive: true });
  await writeFile(`.local/live/${ticker}-filing.html`, html);
  const clean = (s) =>
    s
      .replace(/<[^>]*>/g, " ")
      .replace(/&#160;|&nbsp;|&#xA0;/gi, " ")
      .replace(/&amp;/g, "&")
      .replace(/\s+/g, " ")
      .trim();
  const rows = [...html.matchAll(/<tr\b[^>]*>[\s\S]*?<\/tr>/gi)].map((m) =>
    clean(m[0]),
  );
  const checks = [];
  const criteria = {
    revenue: /total net sales|total revenues|^revenues\b/i,
    operatingCashFlow:
      /cash (generated by|provided by|provided from).*operating activities|net cash.*operating activities/i,
    capex:
      /payments.*(acquisition|property)|purchases of property and equipment/i,
  };
  for (const [key, regex] of Object.entries(criteria)) {
    const value = period.metrics[key].value;
    const expected = new Intl.NumberFormat("en-US", {
      maximumFractionDigits: 3,
    }).format(value);
    const row = rows.find((r) => regex.test(r) && r.includes(expected));
    if (!row) {
      console.log(
        "Candidate rows",
        ticker,
        key,
        expected,
        rows.filter((r) => regex.test(r)).slice(0, 10),
      );
      throw new Error(
        `${ticker} ${key} not matched to an official statement row.`,
      );
    }
    checks.push({ metric: key, usdMillions: value, row, url });
  }
  report.push({ ticker, period: period.end, accession: accn, url, checks });
}
await writeFile(
  ".local/live/filing-verification.json",
  JSON.stringify(report, null, 2),
);
console.log(JSON.stringify(report, null, 2));
